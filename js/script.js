// 获取当前语言
let currentLanguage = localStorage.getItem('language') || 'zh';

// 初始化页面
document.addEventListener('DOMContentLoaded', function() {
    // 设置语言选择器
    const languageSelect = document.getElementById('languageSelect');
    if (languageSelect) {
        languageSelect.value = currentLanguage;
    }
    
    // 应用翻译
    applyTranslations(currentLanguage);
    
    // 处理表单提交
    const contactForm = document.getElementById('contactForm');
    if (contactForm) {
        contactForm.addEventListener('submit', handleFormSubmit);
    }
});

// 改变语言
function changeLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    applyTranslations(lang);
}

// 应用翻译
function applyTranslations(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translation = translations[lang][key] || translations['en'][key] || key;
        
        if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
            element.placeholder = translation;
        } else {
            element.textContent = translation;
        }
    });
    
    // 处理占位符
    const inputs = document.querySelectorAll('[data-i18n-placeholder]');
    inputs.forEach(input => {
        const key = input.getAttribute('data-i18n-placeholder');
        const translation = translations[lang][key] || translations['en'][key] || key;
        input.placeholder = translation;
    });
    
    // 设置页面方向（阿拉伯语从右到左）
    if (lang === 'ar') {
        document.documentElement.dir = 'rtl';
        document.body.dir = 'rtl';
    } else {
        document.documentElement.dir = 'ltr';
        document.body.dir = 'ltr';
    }
}

// 处理表单提交
function handleFormSubmit(e) {
    e.preventDefault();
    
    const name = document.getElementById('name').value;
    const email = document.getElementById('email').value;
    const phone = document.getElementById('phone').value;
    const message = document.getElementById('message').value;
    
    // 创��mailto链接
    const subject = `来自 ${name} 的网站咨询`;
    const body = `姓名: ${name}\n邮箱: ${email}\n电话: ${phone}\n\n咨询内容:\n${message}`;
    
    window.location.href = `mailto:suan147@qq.com?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
    
    // 重置表单
    document.getElementById('contactForm').reset();
    
    alert('感谢您的咨询，我们将尽快回复您！');
}

// 平滑滚动
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function (e) {
        e.preventDefault();
        const target = document.querySelector(this.getAttribute('href'));
        if (target) {
            target.scrollIntoView({
                behavior: 'smooth',
                block: 'start'
            });
        }
    });
});

// 添加滚动动画效果
window.addEventListener('scroll', function() {
    const elements = document.querySelectorAll('.product-card, .feature-item, .stat-item');
    
    elements.forEach(element => {
        const elementTop = element.getBoundingClientRect().top;
        const elementBottom = element.getBoundingClientRect().bottom;
        
        if (elementTop < window.innerHeight && elementBottom > 0) {
            element.style.opacity = '1';
            element.style.transform = 'translateY(0)';
        }
    });
});

// 预加载动画
window.addEventListener('load', function() {
    const elements = document.querySelectorAll('.product-card, .feature-item, .stat-item');
    elements.forEach((element, index) => {
        element.style.opacity = '0';
        element.style.transform = 'translateY(20px)';
        element.style.transition = `all 0.6s ease ${index * 0.1}s`;
    });
});
